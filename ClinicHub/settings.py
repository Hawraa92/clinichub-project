def _normalize_host_for_csrf(host: str) -> str:
    host = (host or "").strip()
    if not host or host == "*":
        return ""

    # If full URL was passed accidentally, extract hostname only
    if host.startswith("http://") or host.startswith("https://"):
        try:
            host = urlparse(host).netloc.split("@")[-1]
        except Exception:
            pass

    # strip port if present
    host = host.split(":")[0].strip()

    # ALLOWED_HOSTS may use ".example.com" -> CSRF should use "*.example.com"
    if host.startswith("."):
        return f"*.{host.lstrip('.')}"
    return host


def _build_csrf_trusted_origins(hosts: list[str], site_url: str) -> list[str]:
    origins: set[str] = set()

    # Add SITE_URL origin (important)
    try:
        parsed = urlparse(site_url)
        if parsed.scheme and parsed.netloc:
            origins.add(f"{parsed.scheme}://{parsed.netloc}")
        else:
            # fallback if SITE_URL is plain host
            host_only = site_url.split("/")[0].split(":")[0].strip()
            if host_only:
                origins.add(f"https://{host_only}")
    except Exception:
        pass

    for h in hosts or []:
        h2 = _normalize_host_for_csrf(h)
        if not h2:
            continue

        # local/testing hosts -> allow both http/https
        if h2 in ("127.0.0.1", "localhost", "testserver"):
            origins.add(f"http://{h2}")
            origins.add(f"https://{h2}")
        elif h2.startswith("*."):
            origins.add(f"https://{h2}")
        else:
            origins.add(f"https://{h2}")

    return sorted(origins)

